# 문제 8) 최대 회의 배정하기 (Lv.3)
# 문제 : (1) 하나의 회의실을 사용하고자 하는 N개의 회의가 있음.
# (2) 각 회의의 시작 시간과 종료 시간이 주어질 때, 서로 겹치지 않게 배정할 수 있는 최대 회의 개수를 구하시오.
# (3) 하나의 회의실에서는 동시에 두 개 이상의 회의를 진행할 수 없음. 
# (4) 회의가 시작되면 종료 시간까지 진행해야 함. 
# (5) 앞 회의의 종료 시간과 다음 회의의 시작 시간이 같으면 연속하여 진행할 수 있음.
# 회의 정보 : 
# 회의 번호 | 시작 시간 | 종료 시간 
# 1 1 4
# 2 3 5
# 3 0 6
# 4 5 7
# 5 8 9 
# 6 5 9
# 회의 1, 4, 5를 순서대로 선택하면 총 3개의 회의를 진행할 수 있음. 
# 풀이 안내 : (1) 먼저 끝나는 회의를 선택하면 다음 회의를 진행할 수 있는 시간이 더 많이 남음. 
# (2) 회의의 시작 시간이나 소요 시간이 아니라 종료 시간을 기준으로 오름차순 정렬한 뒤, 앞에서부터 배정 가능한 회의를 선택하시오.
# 1. 회의 정보를 2차원 리스트에 저장하기 - 각 회의를 [시작 시간, 종료 시간] 형태로 meetings에 append() 함. 
# meetings[i][0]은 i번째 회의의 시작 시간이고, meetings[i][1]은 종료 시간임.
# 2. 종료 시간 기준 선택 정렬하기 - 바깥 반복문의 인덱스는 i는 정렬되지 않은 구간의 첫 번째 위치임. 
# 각 단계에서 min_index = i로 초기화한 뒤, j를 i + 1부터 N - 1까지 순회함. 
# meetings[j][1]이 meetings[min_index][1]보다 작으면 min_index를 j로 갱신함. 
# 안쪽 반복문이 끝난 뒤 min_index != i이면 두 회의 정보 전체를 교환함. 
# 종료 시간이 같은 회의끼리는 추가 정렬 기준을 두지 않아도 됨.
# 3. 정렬한 회의 중 배정 가능한 회의 선택하기 - last_end = 0, count = 0으로 시작함. 
# 정렬된 meetings를 앞에서부터 순회하며 각 회의의 start와 end를 꺼냄.
# start >= last_end이면 회의를 선택하고 count를 1 증가시킨 뒤 last_end를 해당 회의의 end로 갱신함.
# 선택할 수 없는 회의는 건너뜀. 마지막에 count를 출력함.
# 구현 조건 : (1) 회의 정보를 [시작 시간, 종료 시간] 형태의 2차원 리스트로 관리함.
# (2) sort(), sorted(), min()을 사용하지 않고 선택 정렬을 직접 구현함.
# (3) 종료 시간이 가장 작은 회의의 위치를 min_index 변수에 저장함.
# (4) 안쪽 반복문이 끝난 뒤 필요한 경우에만 meetings[i]와 meetings[min_index]를 교환함.
# (5) 마지막으로 선택한 회의의 종료 시간을 last_end 변수에 저장함.
# (6) star >= last_end일 때만 회의를 선택함. 종료 시간과 다음 시작 시간이 같은 경우도 포함함.
# (7) 반복문과 조건문으로 배정 가능한 회의 개수를 계산함.
# 입력 : (1) 첫 번째 줄에 회의 개수 N이 주어짐. (2) 다음 N개의 줄에 각 회의의 시작 시간 S와 종료 시간 E가 주어짐.
# (3) 1 <= N <= 100 (4) 0 <= S < E <= 1,440
# 출력 : 배정할 수 있는 최대 회의 개수를 출력함.
# 입출력 예제 :
# 예제 입력 :
# 6
# 1 4
# 3 5
# 0 6
# 5 7
# 8 9 
# 5 9 
# 예제 출력 :
# 3
