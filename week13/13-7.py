# 문제 7) 하루 동안 최대한 많은 과제 해결하기 (Lv.2)
# 문제 : (1) 학생이 하루 동안 사용할 수 있는 공부 시간은 T분이며, 해결해야 할 과제가 N개 있음.
# (2) 각 과제를 완료하는 데 필요한 시간이 주어질 때, 주어진 시간 안에 완료할 수 있는 최대 과제 개수와 남은 시간을 출력하시오.
# (3) 과제는 한 번에 하나씩 수행함. (4) 과제는 중간에 나누어 수행할 수 없음. 
# (5) 최대 개수의 과제를 완료하는 방법 중 남은 시간이 가장 많은 방법을 선택함.
# 예시 설명 :
# 선택 순서 | 과제 수행 시간 | 남은 시간
# 1 15분 105분
# 2 20분 85분
# 3 25분 60분
# 4 40분 20분
# 다음 과제를 수행하기 위해서는 최소 50분이 필요하므로 종료함.
# 학습 포인트 : (1) 목표를 최대화할 수 있는 선택 기준을 결정함. (2) 선택할 때마다 남은 자원을 갱신함.
# (3) 더 이상 선택할 수 없는 상황에서 반복을 종료함. 
# 입력 : (1) 첫 번째 줄에 정수 N과 T가 주어짐. (2) 두 번째 줄에 N개의 과제 수행 시간이 공백으로 구분되어 주어짐. 
# (3) 1 <= N <= 100 (4) 0 <= T <= 1,440 (5) 1 <= 과제 수행 시간 <= 300
# 출력 : (1) 첫 번째 줄에 완료할 수 있는 최대 과제 개수를 출력함. (2) 두 번째 줄에 남은 시간을 출력함.
# 입출력 예제 :
# 예제 입력 :
# 6 120
# 50 20 40 15 60 25
# 예제 출력 :
# 4
# 20 
