# 문제 4) 기다리는 시간의 합 줄이기 (Lv.3)
# 문제 : (1) 한 대의 기계로 N명의 학생이 차례대로 작업하려고 함. 
# (2) 각 학생의 작업 시간은 서로 다를 수 있으며, 한 번에 한 명만 작업할 수 있음.
# (3) 각 학생의 완료 시간은 자신의 작업 시간과 앞선 학생들의 작업 시간을 모두 더한 값임.
# (4) 모든 학생은 시간 0에 도착하며, 작업 사이에는 쉬는 시간이 없음.
# (5) 작업 순서를 적절히 정하여 모든 학생의 완료 시간의 합을 최소화하시오.
# 예시 설명 : 작업 시간이 짧은 순서인 1,2,3,3,4로 배치함.
# 작업 순서 | 작업 시간 | 완료 시간 
# 1 1 1 
# 2 2 3
# 3 3 6
# 4 3 9
# 5 4 13
# 완료 시간의 합은 1+3+6+9+13=32임.
# 구현 조건 : (1) 정렬 후 반복문으로 완료 시간과 전체 합계를 계산함. (2) sort() 또는 sorted()를 사용해도 됨.
# 입력 : (1) 첫 번째 줄에 학생 수 N이 주어짐. (2) 두 번째 줄에 N명의 작업 시간이 공백으로 구분되어 주어짐.
# (3) 1 <= N <= 100 (4) 1 <= 작업 시간 <= 100
# 출력 : 모든 학생의 완료 시간 합의 최솟값을 출력함.
# 입출력 예제 : 
# 예제 입력 : 
# 5
# 3 1 4 3 2
# 예제 출력 : 
# 32
