# 문제 2) 최소 상자 개수 구하기 (Lv.1)
# 문제 : (1) 물건 N개를 상자에 나누어 담으려고 함. 
# (2) 상자는 각각 8개, 4개, 2개, 1개의 물건을 담을 수 있으며, 종류별로 충분히 있음.
# (3) 사용하는 상자는 반드시 가득 채워야 할 때, 필요한 최소 상자 개수를 출력하시오.
# 예시 설명 : 8개들이 2상자, 4개들이 1상자, 2개들이 1상자, 1개들이 1상자가 필요하므로 총 5상자임.
# 학습 포인트 : (1) 큰 상자부터 채우는 기준을 적용함. 
# (2) 작은 상자 두 개를 바로 위 크기의 상자 하나로 대체할 수 있음을 이해함.
# 입력 : (1) 정수 N이 주어짐. (2) 0 <= N <= 10,000
# 출력 : 필요한 최소 상자 개수를 출력함.
# 입출력 예제 : 
# 예제 입력 : 23
# 예제 출력 : 5
