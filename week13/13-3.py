# 문제 3) 예산 안에서 최대한 많이 구매하기 (Lv.2)
# 문제 : (1) N개의 상품과 예산 B가 주어짐. 
# (2) 각 상품은 최대 한 개만 구매할 수 있으며, 모든 상품은 구매 개수를 셀 때 동일한 한 개로 취급함.
# (3) 예산을 초과하지 않으면서 구매할 수 있는 최대 상품 개수와, 그 개수만큼 구매할 때의 최소 지출 금액을 출력하시오.
# 예시 설명 : 2,000원, 3,000원, 4,000원 상품을 구매하면 총 9,000원으로 3개를 구매할 수 있음.
# 구현 조건 : (1) 상품 가격을 오름차순으로 정렬한 후 선택함. (2) sort() 또는 sorted()를 사용해도 됨.
# 학습 포인트 : (1) 정렬로 선택 순서를 결정함. (2) 남은 예산과 구매 개수를 갱신함. 
# (3) 가장 저렴한 남은 상품도 구매할 수 없다면 반복을 종료함.
# 입력 : (1) 첫 번째 줄에 상품 N과 예산 B가 주어짐. (2) 두 번째 줄에 N개의 상품 가격이 공백으로 구분되어 주어짐.
# (3) 1 <= N <= 100 (4) 0 <= B <= 100,000 (5) 1 <= 상품 가격 <= 10,000
# 출력 : (1) 첫 번째 줄에 최대 구매 개수를 출력함. (2) 두 번째 줄에 해당 개수를 구매하는 데 필요한 최소 지출 금액을 출력함.
# (3) 아무 상품도 구매할 수 없으면 두 줄에 각각 0을 출력함.
# 입출력 예제 :
# 예제 입력 : 
# 5 10000
# 6000 2000 4000 3000 5000
# 예제 출력 :
# 3
# 9000
