# 문제 6) 최대 합 만들기 (Lv.1)
# 문제 : (1) N개의 자연수 중 서로 다른 위치에 있는 K개의 원소를 선택하여 합이 최대가 되도록 하시오.
# (2) 각 원소는 한 번만 선택할 수 있음. 
# 예시 설명 : 가장 큰 세 원소인 50, 40, 30을 선택하면 합은 120임.
# 학습 포인트 : (1) 내림차순 정렬을 이용하여 선택 순서를 결정함. (2) 목표에 따라 적절한 정렬 방향을 판단함.
# 입력 : (1) 첫 번째 줄에 정수 N과 K가 주어짐. (1 <= K <= N <= 100)
# (2) 두 번째 줄에 N개의 자연수가 공백으로 구분되어 주어짐. (3) 1 <= 각 자연수 <= 1,000
# 출력 : 선택한 K개 원소의 합의 최댓값을 출력함.
# 입출력 예제 :
# 예제 입력 : 
# 6 3
# 10 40 20 50 30 5
# 예제 출력 : 
# 120 

N, K = map(int, input().split())
numbers = list(map(int, input().split()))

numbers.sort(reverse = True)
total = 0

for i in range(K):
  total += numbers[i]

print(total)
