# 문제 1) 윤년 판독기 (Lv.1))
# 문제 : 연도 N(정수)를 입력받아, 윤년인지 아닌지 판독하는 프로그램을 작성하시오.
# 입력 : (1) 정수 N, (2) 1900 <= N <= 3000
# 윤년 조건 : (1) 연도가 4로 나누어 떨어지면 윤년이다. (2) 100으로 나누어 떨어지는 연도는 제외한다.
# (3) 400으로 나누어 떨어지는 연도는 윤년이다.
# 출력 (연도 입력 -> 윤년 판독 -> 출력) : 연도를 입력하시오 : 2012, 2012년은 윤년입니다.

print("연도를 입력하시오: ", end = " ")
N = int(input())

if N % 4 == 0:
  if N % 100 != 0:
    print(f"{N}년은 윤년입니다.")
  else:
    if N % 400 == 0:
      print(f"{N}년은 윤년입니다.")
    else:
      print(f"{N}년은 윤년이 아닙니다.")
else:
  print(f"{N}년은 윤년이 아닙니다.")
