# 문제 7) 테두리가 있는 다이아몬드 (Lv.3)
# 문제 : 홀수 N을 입력받아 가로와 세로가 N칸인 영역에 속이 채워진 다이아몬드를 출력하시오.
# 다이아몬드의 테두리는 *로, 속은 +로 출력하시오.
# 입력 : 홀수 N (5 <= N <= 21)
# 출력 : (1) 문자열 반복 연산을 이용하여 한 줄 전체를 한 번에 출력하지 않음.
# (2) 다이아몬드의 가장 위와 아래에는 * 하나만 출력함.
# (3) 다이아몬드의 좌우 경계에는 *을 출력함. 
# (4) 다이아몬드 내부에는 +를 출력함. 
# (5) 다이아몬드 외부에는 공백을 출력함.
# (6) 각 위치가 테두리인지 -> 내부인지 -> 외부인지 조건문을 이용하여 판단함.

N = int(input())

# 교수님식 코드
N = int(input())

center = N // 2

for i in range(N):
    for j in range(N):
        distance = abs(i - center) + abs(j - center)

        if distance == center:
            # 다이아몬드 테두리
            print("*", end="")
        elif distance < center:
            # 다이아몬드 내부
            print("+", end="")
        else:
            # 다이아몬드 외부
            print(" ", end="")

    print()
