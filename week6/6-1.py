# 문제 1) 요일 출력하기 (Lv.1)
# 문제 : 정수 N을 입력받아 해당하는 요일을 출력하시오. 반드시 match-case를 사용하시오.
# 입력 : 정수 N 
# 요일 조건 : 
# 1-월요일, 2-화요일, 3-수요일, 4-목요일, 5-금요일, 6,7-주말, 그 외-잘못된 입력입니다.
# 출력 (입력한 N에 맞는 요일 출력) : (1) 숫자를 입력하세요:6 (2) 주말

N = int(input()) # 요일 

match N:
  case 1:
    print("월요일")
  case 2:
    print("화요일")
  case 3:
    print("수요일")
  case 4:
    print("목요일")
  case 5:
    print("금요일")
  case 6 | 7:
    print("주말")
  case _:
    print("잘못된 입력입니다.")
