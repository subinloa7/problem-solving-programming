# 문제 2) 선택한 값 바꾸기 (Lv.1)
# 문제 : (1) 다섯 개의 정수를 리스트에 저장한 뒤, K번째 값을 X로 변경하시오.
# (2) 변경된 리스트의 모든 값을 순서대로 출력하시오.
# 입력 : (1) 첫 번째 줄에 정수 다섯 개가 주어짐 (2) 두 번째 줄에 정수 K와 X가 주어짐 (3) 1 <= K <= 5
# 출력조건 : 변경된 리스트의 값을 공백으로 구분하여 출력함 
# ex) 10 20 30 40 50 
# 2 99
# 10 99 30 40 50 

data = list(map(int, input().split()))
K, X = map(int, input().split())
data[K-1]=X
print(*data)

