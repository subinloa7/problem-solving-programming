# 문제 1) 버블 정렬 한 바퀴 (Lv.1)
# 문제 : (1) N개의 정수가 주어짐. 왼쪽부터 오른쪽으로 인접한 두 원소를 차례대로 비교하고, 왼쪽 값이 더 크면 두 값을 교환하시오.
# (2) 교환한 결과를 반영하여 다음 쌍을 비교하며, 마지막 쌍까지 비교하면 종료하시오.
# 구현 조건 : 반복문 하나로 인덱스 i와 i + 1에 있는 값을 비교함.
# 입력 : (1) 첫 번째 줄에 정수 N이 주어짐. (1 <= N <= 100)
# (2) 두 번째 줄에 N개의 정수가 공백으로 구분되어 주어짐. (-1,000 <= 각 정수 <= 1,000)
# 출력 : (1) 한 바퀴를 마친 리스트를 공백으로 구분하여 한 줄에 출력함. 
# (2) N = 1이면 원소를 그대로 출력함.
# 입출력 예제 :
# 예제 입력 :
# 5
# 5 3 4 1 2
# 예제 출력 :
# 3 4 1 2 5

N = int(input())
numbers = list(map(int, input().split()))

for i in range(N - 1):
  if numbers[i] > numbers[i + 1]:
    numbers[i], numbers[i + 1] = numbers[i + 1], numbers[i]

print(*numbers)
