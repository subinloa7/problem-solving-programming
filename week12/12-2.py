# 문제 2) 교환이 없으면 멈추는 버블 정렬 (Lv.2)
# 문제 : (1) N개의 정수를 버블 정렬로 오름차순 정렬하시오.
# (2) 한 바퀴가 끝날 때마다 오른쪽에서 위치가 확정된 원소를 다음 비교 범위에서 제외하시오.
# (3) 한 바퀴 동안 교환이 한 번도 일어나지 않으면 정렬을 종료하시오.
# (4) 비교할 인접 원소가 더 이상 없으면 추가로 바퀴 수를 세지 않음.
# 구현 조건 : (1) 각 바퀴를 시작할 때 교환 여부를 나타내는 변수를 초기화함.
# (2) 두 값이 같으면 교환하지 않음.
# 입력 : (1) 첫 번째 줄에 정수 N이 주어짐. (1 <= N <= 100)
# (2) 두 번째 줄에 N개의 정수가 공백으로 구분되어 주어짐. (-1,000 <= 각 정수 <= 1,000)
# 출력 : (1) 첫 번째 줄에 정렬된 리스트를 공백으로 구분하여 출력함.
# (2) 두 번째 줄에 수행한 바퀴 수를 출력함. 교환 없이 종료 한 바퀴도 포함하며, N = 1이면 0을 출력함.
# 입출력 예제 :
# 예제 입력 :
# 5
# 2 1 3 4 5
# 예제 출력 :
# 1 2 3 4 5
# 2
