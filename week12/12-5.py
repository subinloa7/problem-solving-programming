# 문제 5) 선택 정렬로 내림차순 정렬하기 (Lv.2)
# 문제 : (1) N명의 시험 점수를 입력받아 선택 정렬로 높은 점수부터 낮은 점수 순서로 정렬하시오.
# (2) 각 단계에서 정렬되지 않은 구간의 최댓값을 선택하여 앞쪽에 배치하시오.
# 구현 조건 : (1) sort(), sorted(), max(), reverse()를 사용하지 않음.
# (2) 반복문을 감소 방향으로 실행하는 것만으로 해결하지 않고, 최댓값을 선택하는 비교 조건을 작성함.
# (3) 중복된 점수도 모두 유지함.
# 입력 : (1) 첫 번째 줄에 학생 수 N이 주어짐. (1 <= N <= 100)
# (2) 두 번째 줄에 N명의 점수가 공백으로 구분되어 주어짐. (0 <= 점수 <= 100)
# 출력 : 점수를 내림차순으로 정렬하여 공백으로 구분하여 제출함.
# 입출력 예제 :
# 예제 입력 : 
# 6
# 75 90 60 90 85 100
# 예제 출력 :
# 100 90 90 85 75 60
