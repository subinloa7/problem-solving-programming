# 문제 3) 짝수를 먼저 배치하는 버블 정렬 (Lv.3)
# 문제 : (1) N개의 정수를 버블 정렬로 다음 기준에 따라 정렬하시오.
# (a) 모든 짝수를 홀수보다 앞에 배치함. 0도 짝수임.
# (b) 짝수끼리, 홀수끼리는 각각 오름차순으로 배치함.
# 구현 조건 : (1) 짝수와 홀수를 별도의 리스트로 나누지 않고, 입력 리스트에서 인접한 두 원소만 교환함.
# (2) 왼쪽부터 오른쪽으로 비교하며, 매 바퀴가 끝나면 오른쪽에서 위치가 확정된 원소를 다음 비교 범위에서 제외함.
# *생각해 볼 점 : 인접한 두 값이 1, 8일때와 8, 2일 때, 각각 어떤 기준으로 교환 여부를 판단해야 하는가?
# 입력 : (1) 첫 번째 줄에 정수 N이 주어짐. (1 <= N <= 100)
# (2) 두 번째 줄에 N개의 정수가 공백으로 구분되어 주어짐. (-1,000 <= 각 정수 <= 1,000)
# 출력 : 정렬된 리스트를 공백으로 구분하여 한 줄에 출력함 
# 입출력 예제 :
# 예제 입력 :
# 8
# 7 4 -3 2 0 1 -2 4
# 예제 출력 :
# -2 0 2 4 4 -3 1 7
