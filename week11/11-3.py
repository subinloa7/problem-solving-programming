# 문제 3) 재고가 부족한 상품 확인하기 (Lv.2)
# 문제 : (1) N개 상품의 재고 수량과 목표 재고량 K가 주어짐. 
# (2) 재고가 K보다 적은 상품의 번호와, 각 부족 상품의 재고를 K개까지 채우는 데 필요한 수량의 합을 출력하시오.
# (3) 상품 번호는 1번부터 시작함. 예제에서 1번 상품은 3개, 3번은 7개, 5번은 2개가 부족하므로 총 12개가 필요함.
# 구현 조건 : 리스트를 한 번 순회하면서 부족한 상품의 번호를 저장하고, 부족한 수량을 누적함.
# 입력 : (1) 첫 번째 줄에 상품 N과 목표 재고량 K가 주어짐. (1 <= N <= 100, 1 <= K <= 1,000)
# (2) 두 번째 줄에 N개의 재고 수량이 공백으로 구분되어 주어짐. (0 <= 재고 수량 <= 1,000)
# 출력 : (1) 첫 번째 줄에 재고가 부족한 상품의 번호를 작은 순서대로 공백으로 구분하여 출력함. 
# (2) 부족한 상품이 없으면 NONE을 출력함.
# (3) 두 번째 줄에 필요한 수량의 합을 출력함. 부족한 상품이 없으면 0을 출력함.
# 입출력 예제 :
# 예제 입력 :
# 5 10 
# 7 10 3 15 8 
# 예제 출력 :
# 1 3 5
# 12
