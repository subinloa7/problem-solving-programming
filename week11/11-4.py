# 문제 4) 평균에 가장 가까운 학생 찾기 (Lv.3)
# 문제 : N명의 시험 점수가 주어짐. 전체 평균을 계산한 뒤, 평균과 점수의 차이의 절댓값이 가장 작은 학생을 찾으시오.
# (2) 평균에 똑같이 가까운 학생이 여러 명이면 번호가 가장 작은 학생을 선택하시오. 학생 번호는 1번부터 시작함.
# (3) 첫 번째 예제에서 전체 평균은 70점이며, 5번 학생의 점수가 평균과 일치함. 두 번째 예제에서 평균은 70점이고. 
# 2번과 3번 학생이 모두 평균과 10점 차이이므로 2번 학생을 선택함.
# 구현 조건 : (1) 첫 번째 순회에서 점수를 누적하여 평균을 계산함. sum()은 사용하지 않음.
# (2) 두 번째 순회에서 각 점수와 평균의 차이를 비교함. min()과 정렬은 사용하지 않으며, abs()는 사용 가능함.
# (3) 현재까지 가장 작은 차이와 해당 학생의 위치를 함께 저장함.
# 입력 : (1) 첫 번째 줄에 학생 수 N이 주어짐. (1 <= N <= 100)
# (2) 두 번째 줄에 N명의 점수가 공백으로 구분되어 주어짐. (0 <= 점수 <= 100)
# 출력 : (1) 선택된 학생의 번호와 점수를 공백으로 구분하여 출력함.
# (2) 평균은 반올림하지 않고 비교함.
# 입출력 에제 :
# 예제 입력 1 :
# 5 
# 90 68 72 50 70 
# 예제 출력 1 :
# 5 70 
# 예제 입력 2 :
# 4
# 50 60 80 90 
# 예제 출력 2 :
# 2 60 
