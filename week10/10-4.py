# 문제 4) 파일 확장자 추출하기 (Lv.1)
# 문제 : (1) 파일 이름을 입력받아 확장자를 소문자로 출력하시오.
# (2) 확장자는 마지막 마침표(.) 뒤의 문자열을 의미함.
# (3) split(\".\")으로 문자열을 나눔. 
# (4) 음수 인덱스로 마지막 요소에 접근함. 
# (5) lower()로 대소문자를 통일 
# 입력 : (1) 파일 이름 한 줄이 주어짐. 파일 이름에는 마침표가 하나 이상 포함됨. 
# (2) 마지막 문자는 마침표가 아니며, 공백은 포함되지 않음. 문자열 길이는 3 이상 100 이하임.
# ex) PYTHON.DEV.PDF -> pdf
# ex) PYTHON.DEV.PDF.XLSX -> xlsx

name = input()
parts = name.split(".")

print(parts[-1].lower())
