# 문제 3) 문자 사이에 구분자 넣기 (Lv.2)
# 문제 : 단어를 전달받아 각 문자 사이에 하이픈 (-) 을 넣은 문자열을 반환하는 함수 add_separator(text)를 작성하시오.
# 구현 조건 : 함수 내부에서 반복문을 사용함. join()은 사용하지 않음.
# 제출 안내 : 함수를 정의한 뒤, 표준 입력으로 단어를 읽어 함수를 호출하고 반환된 문자열을 출력하시오.
# 학습 목표 : 반복문으로 문자열을 누적하고, 마지막 구분자가 남지 않도록 구성함.
# 입력 : 길이가 1 이상 30 이하인 영문 단어가 주어짐.
# 출력 : 각 문자 사이에 하이픈을 넣은 결과를 출력함. 첫 문자 앞과 마지막 문자 뒤에는 하이픈을 넣지 않음.
# 예제 입력 : PYTHON
# 예제 출력 : P-Y-T-H-O-N
