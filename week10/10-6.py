# 문제 6) 비밀번호 규칙 검사하기 (Lv.3)
# 문제 : 문자열을 전달받아 다음 조건을 모두 만족하면 True, 하나라도 만족하지 못하면 False를 반환하는 함수 is_vaild_password(password)를 작성하시오.
# (1) 길이가 8 이상 20 이하이어야 함.
# (2) 영문 대문자가 하나 이상 포함되어야 함.
# (3) 영문 소문자가 하나 이상 포함되어야 함.
# (4) 숫자가 하나 이상 포함되어야 함.
# (5) 특수문자 !, @, # 중 하나 이상이 포함되어야 함.
# (6) 영문 대소문자, 숫자, !, @, # 이외의 문자는 포함할 수 없음.
# 구현 조건 : 함수 내부에서 반복문과 조건문으로 문자를 검사함. 정규표현식은 사용하지 않음. 입력된 비밀번호의 공백을 임의로 제거하지 않음.
# 제출 안내 : 함수를 정의한 뒤, 표준 입력으로 N과 비밀번호 N개를 읽고 각 비밀번호를 함수에 전달하시오. 반환값이 True이면 VALID, False이면 INVALID를 출력하시오. 예제의 마지막 비밀번호에는 ! 뒤에 공백이 있으므로 허용되지 않는 문자가 포함된 경우임.
# 학습 목표 : 문자별 조건 검사, 조건 충족 여부 저장, 함수의 논리값 반환을 결합함.
# 입력 : (1) 첫 번째 줄에 검사할 비밀번호 수 N이 주어짐 (1 <= N <= 20). 다음 N개의 줄에 비밀번호가 하나씩 주어짐.
# (2) 각 비밀번호의 길이는 1 이상 50 이하임. 입력 문자열에는 공백이 포함될 수 있음.
# 출력 : 각 비밀번호가 조건을 만족하면 VALID, 그렇지 않으면 INVALID를 한 줄씩 출력함.
# 예제 입력 : 
# 5
# Python1!
# python1!
# PYTHON1!
# Python12
# Python1!
# 예제 출력 :
# VALID
# INVALID
# INVALID
# INVALID
# INVALID
