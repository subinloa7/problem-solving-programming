# 문제 7) 연속된 문자 압축하기 (Lv.3)
# 문제 : (1) 문자열에서 같은 문자가 연속으로 등장하는 구간을 문자와 등장 횟수로 압축하시오.
# (2) 문자열을 전달받아 압축 결과를 반환하는 함수 compress_text(text)를 작성하시오.
# (3) 같은 문자가 연속되면 하나의 구간으로 처리함. 한 번만 등장한 문자도 횟수 1을 붙임.
# (4) 같은 문자라도 떨어져 있으면 서로 다른 구간으로 처리함. 
# (5) 예를 들어 AAABBACCCC는 A3B2A1C4로 압축함.
# 구현 조건 : (1) 함수 내부에서 반복문과 조건문을 사용함.
# (2) count()와 외부 라이브러리는 사용하지 않음.
# (3) 등장 횟수는 str()로 변환하여 결과 문자열에 연결할 수 있음.
# (4) 입력과 출력은 함수 밖에서 처리함. 
# 제출 안내 : (1) 함수를 정의한 뒤, 함수 밖에서 표준 입력으로 문자열을 읽어 함수를 호출하고 반환된 압축 문자열을 출력하시오.
# (2) 영문과 공백으로 구성된 문장 한 줄이 주어짐. 단어는 하나 이상이며, 문자열의 길이는 1 이상 100 이하임. 
# (3) 단어 사이에 여러 개의 공백이 있거나 문장 앞뒤에 공백이 있을 수 있음. 
# ex) AAABBACCCC -> A3B2A1C4
# ex) ABCDEFGHI -> A1B1C1D1E1F1G1H1I1
