# 문제 5) 단어의 첫 글자로 약어 만들기 (Lv.2)
# 문제 : (1) 여러 단어로 이루어진 문장을 입력받아, 각 단어의 첫 글자를 대문자로 연결한 약어를 출력하시오.
# (2) 문자열을 전달받아 약어를 반환하는 함수 make_abbreviation(text)를 작성하시오,
# 구현 조건 : (1) split()으로 각 문장을 단어 단위로 나눔.
# (2) 반복문으로 각 단어의 첫 글자를 추출하여 연결함.
# (3) upper()로 대문자로 변환함. 입력과 출력은 함수 밖에서 처리함.
# 입력 : (1) 영문과 공백으로 구성된 문장 한 줄이 주어짐. 단어는 하나 이상이며, 문자열의 길이는 1 이상 100 이하임.
# (2) 단어 사이에 여러 개의 공백이 있거나 문장 앞뒤에 공백이 있을 수 있음.
# 출력 : 각 단어의 첫 글자를 대문자로 연결하여 출력함.
# ex) artificial intelligence -> AI
# ex) Problem solving -> PS
