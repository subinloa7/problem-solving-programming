# 문제 2) 몫과 나머지의 합 (Lv.1)
# 문제 : (1) 두 정수 A, B를 입력받아 A를 B로 나눈 몫과 나머지를 더한 값을 출력하시오.
# (2) 단, 이 연산을 A, A+1, A+2, A+3, A+4에 대해 각각 수행하여 출력하시오.
# 입력 : (1) 두 정수 A, B가 주어짐. (2) 1 <= A, B <= 100
# 출력 : A, A+1, A+2, A+3, A+4

A, B = map(int, input().split())

for i in range(A, A + 5):
  print(i // B + i % B)
