# 문제 6) 자릿수 가중치 계산 (Lv.2)
# 문제 : 자연수 N을 입력받아 일의 자리에는 1, 십의 자리에는 2, 백의 자리에는 3과 같이 자릿수마다 가중치를 증가시켜 곱한 후 모두 더하시오.
# 입력 : (1) 자연수 N이 주어짐 (2) N <= 99999
# 출력 : 입력 1234, 출력 20 
# 4x1=4, 3x2=6, 2x3=6, 1x4=4, 4+6+6+4=20

N = int(input())

일의자리 = N % 10
십의자리 = N // 10 % 10 
백의자리 = N // 100 % 10 
천의자리 = N // 1000 % 10 
만의자리 = N // 10000

print((일의자리*1)+(십의자리*2)+(백의자리*3)+(천의자리*4)+(만의자리*5))

# 교수님식 코드
N = int(input())
weight = 1
total = 0

while N > 0:
    total += (N % 10) * weight  # 일의 자리 숫자에 가중치를 곱해 합산
    N = N // 10                # 일의 자리 제거
    weight += 1                # 다음 자리의 가중치 증가

print(total)
