# 문제 4) 숫자 분해하기(Lv.1)
# 문제 : 자연수 N을 입력받아, 일의 자리부터 한 자리씩 출력하시오.
# 입력 : (1) 자연수 N이 주어짐 (2) 0 <= N <= 99999
# 출력 : (1) 입력 58321 
# (2) 1
# 2
# 3
# 8
# 5

N = int(input())

일의자리 = N % 10
십의자리 = N // 10 % 10
백의자리 = N // 100 % 10
천의자리 = N // 1000 % 10
만의자리 = N // 10000

print(일의자리)
print(십의자리)
print(백의자리)
print(천의자리)
print(만의자리)
