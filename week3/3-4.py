# 문제 : 정수 N을 입력받아 첫 번째 줄에는 별 1개, 두 번째 줄에는 별 2개를 출력하는 방식으로, N번째 줄까지 별을 출력하시오.
# 입력 : 정수 N이 주어짐 (1 <= N <= 20)
# 출력 : (1) 총 N개의 줄에 별을 출력함 (2) i번째 줄에는 별을 i개 출력하며, 별 사이에는 공백을 넣지 않음

N = int(input())
for i in range(N):
  print("*" * (i + 1))

# 교수님식 코드 
# 출력할 줄 수 입력 
N = int(input()) # N = 5

# 1부터 N까지 반복
for i in range(1, N+1):
  print("*" * i)
