# 문제 : 가지고 있는 돈으로 같은 가격의 간식을 여러 개 구매하려고 함. 
# 가지고 있는 돈, 간식 한 개의 가격, 구매할 개수를 입력받아 총 구매 금액과 남은 돈을 출력하시오.
# 입력 : (1) 한 줄에 세 정수 M P N이 공백으로 구분되어 주어짐 
# (2) M : 가지고 있는 돈, P : 간식 한 개의 가격, N : 구매할 개수 
# (3) 1 <= M <= 100,000, 1 <= P <= 10,000, 1<= N <= 10 
# (4) 총 구매 금액은 가지고 있는 돈을 넘지 않음
# 출력 : (1) 첫 번째 줄에 총 구매 금액을 출력함
# (2) 두 번째 줄에 남은 돈을 출력함 
# (3) 단위나 안내 문구 없이 숫자만 출력함

M, P, N = map(int, input().split())

total = P * N # 총 구매 금액
total_cash = M - total # 남은 돈 

print(total)
print(total_cash)
