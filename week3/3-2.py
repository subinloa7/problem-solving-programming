# 문제 : 이름과 좋아하는 음식을 각각 입력받아, 아래 형식으로 출력하시오.
# 입력 : (1) 첫 번째 줄에 이름이 주어짐 (2) 두 번째 줄에 좋아하는 음식이 주어짐 
# 출력 : (1) 첫 번째 줄에 이름 : 이름을 출력함 (2) 두 번째 줄에 좋아하는 음식 : 음식을 출력함 (3) 콜론 뒤에는 공백 한 칸을 넣음 

name = input()
favorite_food = input()
print("이름:", name)
print("좋아하는 음식:", favorite_food)

