# 문제 5) 마름모 모양의 별 찍기 (Lv.2)
# 문제 : 정수 N을 입력받아 마름모 형태의 별을 출력하시오. 첫 번째 줄에는 별 1개를 출력하고, N번째 줄까지 별의 개수를 2개씩 늘린 뒤,
# 이후에는 2개씩 줄여 마지막 줄에 별 1개를 출력하시오. 각 줄은 앞쪽에 공백을 넣어 가운데 정렬하시오.
# 입력 : (1) 정수 N이 주어짐 (1 <= N <= 20) (2) N은 마름모의 첫 번째 줄부터 가운데 줄까지의 줄 수를 의미함
# 출력 : (1) 총 2N-1개의 줄에 별을 출력함 (2) 첫 번째 줄부터 N번째 줄까지, i번째 줄에는 앞쪽 공백 N-i개와 별 2i-1개를 출력ㅎ함
# (3) N번째 줄 이후에는 위쪽과 대칭이 되도록 별의 개수를 줄여 출력함 
# (4) 별 사이와 각 줄의 마지막에는 공백을 넣지 않음

N = int(input())
for i in range(1, N+1):
  print(" " * (N - i) + "*" * (2 * i - 1))
for i in range(N-1, 0, -1):
  print(" " * (N - i) + "*" * (2 * i - 1))

# 교수님식 코드 
N = int(input())
# 위쪽 : 별의 개수가 증가함
for i in range(1, N+1):
  spaces = N - i
  stars = 2 * i - 1
  print(" " * spaces + "*" * stars)
# 아래쪽 : 별의 개수가 감소함
for i in range(N-1, 0, -1):
  spaces = N - i
  stars = 2 * i - 1
  print(" " * spaces + "*" * stars)
